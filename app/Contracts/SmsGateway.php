<?php

namespace App\Contracts;

/**
 * قرارداد اتصال به هر سرویس پیامک ایرانی.
 *
 * هنوز تصمیم گرفته نشده کدام سرویس (کاوه‌نگار، ملی‌پیامک، فراپیامک و ...)
 * استفاده شود؛ به همین دلیل الان فقط این قرارداد + یک پیاده‌سازی پیش‌فرض
 * که در لاگ می‌نویسد (LogSmsGateway) ساخته شده. وقتی سرویس انتخاب شد،
 * کافی است یک کلاس تازه این قرارداد را پیاده کند و در
 * AppServiceProvider::register() جایگزین LogSmsGateway شود — هیچ‌جای
 * دیگر سامانه (TicketObserver و غیره) نیازی به تغییر ندارد.
 */
interface SmsGateway
{
    /**
     * ارسال پیامک. مقدار برگشتی فقط برای لاگ/گزارش خطا استفاده می‌شود؛
     * هرگز نباید ارسال‌نشدن پیامک جریان اصلی برنامه (مثل ثبت تیکت) را متوقف کند.
     */
    public function send(string $toMobile, string $message): bool;
}
